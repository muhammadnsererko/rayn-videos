BEGIN;

CREATE TABLE IF NOT EXISTS vjs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS vjs_name_normalized_idx ON vjs (LOWER(BTRIM(name)));

ALTER TABLE movies
    ADD COLUMN IF NOT EXISTS backdrop_url TEXT,
    ADD COLUMN IF NOT EXISTS poster_key TEXT,
    ADD COLUMN IF NOT EXISTS backdrop_key TEXT,
    ADD COLUMN IF NOT EXISTS vj_id BIGINT;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'movies_vj_id_fkey'
          AND conrelid = 'movies'::regclass
    ) THEN
        ALTER TABLE movies
            ADD CONSTRAINT movies_vj_id_fkey
            FOREIGN KEY (vj_id) REFERENCES vjs(id) ON DELETE RESTRICT;
    END IF;
END
$$;

CREATE INDEX IF NOT EXISTS movies_vj_id_idx ON movies (vj_id);

COMMIT;
