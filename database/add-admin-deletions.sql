BEGIN;

ALTER TABLE movies
    ADD COLUMN IF NOT EXISTS deletion_pending BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE series
    ADD COLUMN IF NOT EXISTS deletion_pending BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE seasons
    ADD COLUMN IF NOT EXISTS deletion_pending BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE episodes
    ADD COLUMN IF NOT EXISTS deletion_pending BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE episode_video_versions
    ADD COLUMN IF NOT EXISTS deletion_pending BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE IF NOT EXISTS admin_deletion_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    operation VARCHAR(24) NOT NULL CHECK (operation IN ('delete_records', 'cleanup_only')),
    entity_type VARCHAR(32) NOT NULL
        CHECK (entity_type IN ('movie', 'series', 'season', 'episode', 'episode_version', 'movie_video_replacement')),
    entity_id VARCHAR(64) NOT NULL,
    target_record_ids JSONB NOT NULL CHECK (jsonb_typeof(target_record_ids) = 'array'),
    status VARCHAR(24) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'processing', 'cleanup_failed', 'finalization_failed', 'completed')),
    attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    last_error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    completed_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS admin_deletion_jobs_pending_idx
    ON admin_deletion_jobs (status, created_at DESC)
    WHERE status <> 'completed';

CREATE TABLE IF NOT EXISTS admin_deletion_objects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT NOT NULL REFERENCES admin_deletion_jobs(id) ON DELETE CASCADE,
    object_key TEXT NOT NULL CHECK (object_key <> ''),
    status VARCHAR(16) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'deleted', 'shared')),
    target_reference_count INTEGER NOT NULL DEFAULT 0 CHECK (target_reference_count >= 0),
    last_error TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (job_id, object_key)
);

CREATE INDEX IF NOT EXISTS admin_deletion_objects_key_status_idx
    ON admin_deletion_objects (object_key, status);

COMMIT;
