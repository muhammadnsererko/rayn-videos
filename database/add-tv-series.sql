BEGIN;

CREATE TABLE IF NOT EXISTS series (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    poster_url TEXT,
    backdrop_url TEXT,
    poster_key TEXT,
    backdrop_key TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS series_created_at_idx ON series (created_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS seasons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    series_id BIGINT NOT NULL REFERENCES series(id) ON DELETE RESTRICT,
    season_number INTEGER NOT NULL CHECK (season_number > 0),
    release_year SMALLINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (series_id, season_number)
);

CREATE TABLE IF NOT EXISTS episodes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_id BIGINT NOT NULL REFERENCES seasons(id) ON DELETE RESTRICT,
    episode_number INTEGER NOT NULL CHECK (episode_number > 0),
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    duration_minutes SMALLINT NOT NULL CHECK (duration_minutes BETWEEN 1 AND 1000),
    tier VARCHAR(8) NOT NULL CHECK (tier IN ('free', 'vip')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (season_id, episode_number)
);

CREATE INDEX IF NOT EXISTS episodes_tier_created_at_idx ON episodes (tier, created_at DESC);

CREATE TABLE IF NOT EXISTS episode_video_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    episode_id BIGINT NOT NULL REFERENCES episodes(id) ON DELETE RESTRICT,
    vj_id BIGINT NOT NULL REFERENCES vjs(id) ON DELETE RESTRICT,
    r2_key TEXT NOT NULL UNIQUE,
    is_current BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS episode_video_versions_current_vj_idx
    ON episode_video_versions (episode_id, vj_id)
    WHERE is_current;
CREATE INDEX IF NOT EXISTS episode_video_versions_episode_id_idx
    ON episode_video_versions (episode_id);
CREATE INDEX IF NOT EXISTS episode_video_versions_vj_id_idx
    ON episode_video_versions (vj_id);

COMMIT;
