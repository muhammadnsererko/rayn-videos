CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role VARCHAR(16) NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'vip', 'admin')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS admin_activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    action VARCHAR(80) NOT NULL,
    entity_type VARCHAR(32) NOT NULL,
    entity_id VARCHAR(64) NOT NULL,
    summary VARCHAR(500) NOT NULL,
    details JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS admin_activity_created_at_idx
    ON admin_activity (created_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS vjs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS vjs_name_normalized_idx ON vjs (LOWER(BTRIM(name)));

CREATE TABLE IF NOT EXISTS movies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    tier VARCHAR(8) NOT NULL CHECK (tier IN ('free', 'vip')),
    release_year SMALLINT NOT NULL CHECK (release_year >= 1888),
    duration_minutes SMALLINT NOT NULL CHECK (duration_minutes BETWEEN 1 AND 1000),
    poster_url TEXT,
    backdrop_url TEXT,
    poster_key TEXT,
    backdrop_key TEXT,
    vj_id BIGINT REFERENCES vjs(id) ON DELETE RESTRICT,
    r2_key TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deletion_pending BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS movies_tier_created_at_idx ON movies (tier, created_at DESC);
CREATE INDEX IF NOT EXISTS movies_vj_id_idx ON movies (vj_id);

CREATE TABLE IF NOT EXISTS series (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    poster_url TEXT,
    backdrop_url TEXT,
    poster_key TEXT,
    backdrop_key TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deletion_pending BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS series_created_at_idx ON series (created_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS seasons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    series_id BIGINT NOT NULL REFERENCES series(id) ON DELETE RESTRICT,
    season_number INTEGER NOT NULL CHECK (season_number > 0),
    release_year SMALLINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deletion_pending BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (series_id, season_number)
);

CREATE TABLE IF NOT EXISTS episodes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_id BIGINT NOT NULL REFERENCES seasons(id) ON DELETE RESTRICT,
    episode_number INTEGER NOT NULL CHECK (episode_number > 0),
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    duration_minutes SMALLINT NOT NULL CHECK (duration_minutes BETWEEN 1 AND 1000),
    tier VARCHAR(8) NOT NULL CHECK (tier IN ('free', 'vip')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deletion_pending BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (season_id, episode_number)
);

CREATE INDEX IF NOT EXISTS episodes_tier_created_at_idx ON episodes (tier, created_at DESC);

CREATE TABLE IF NOT EXISTS episode_video_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    episode_id BIGINT NOT NULL REFERENCES episodes(id) ON DELETE RESTRICT,
    vj_id BIGINT NOT NULL REFERENCES vjs(id) ON DELETE RESTRICT,
    r2_key TEXT NOT NULL UNIQUE,
    is_current BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deletion_pending BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE UNIQUE INDEX IF NOT EXISTS episode_video_versions_current_vj_idx
    ON episode_video_versions (episode_id, vj_id)
    WHERE is_current;
CREATE INDEX IF NOT EXISTS episode_video_versions_episode_id_idx
    ON episode_video_versions (episode_id);
CREATE INDEX IF NOT EXISTS episode_video_versions_vj_id_idx
    ON episode_video_versions (vj_id);

CREATE TABLE IF NOT EXISTS password_reset_tokens (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS admin_deletion_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    operation VARCHAR(24) NOT NULL CHECK (operation IN ('delete_records', 'cleanup_only')),
    entity_type VARCHAR(32) NOT NULL
        CHECK (entity_type IN ('movie', 'series', 'season', 'episode', 'episode_version', 'movie_video_replacement')),
    entity_id VARCHAR(64) NOT NULL,
    target_record_ids JSONB NOT NULL CHECK (jsonb_typeof(target_record_ids) = 'array'),
    status VARCHAR(24) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'processing', 'cleanup_failed', 'finalization_failed', 'completed')),
    attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    last_error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    completed_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS admin_deletion_jobs_pending_idx
    ON admin_deletion_jobs (status, created_at DESC)
    WHERE status <> 'completed';

CREATE TABLE IF NOT EXISTS admin_deletion_objects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT NOT NULL REFERENCES admin_deletion_jobs(id) ON DELETE CASCADE,
    object_key TEXT NOT NULL CHECK (object_key <> ''),
    status VARCHAR(16) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'deleted', 'shared')),
    target_reference_count INTEGER NOT NULL DEFAULT 0 CHECK (target_reference_count >= 0),
    last_error TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (job_id, object_key)
);

CREATE INDEX IF NOT EXISTS admin_deletion_objects_key_status_idx
    ON admin_deletion_objects (object_key, status);